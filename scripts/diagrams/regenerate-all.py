#!/usr/bin/env python3
"""Rebuild every registered diagram; optionally export PNGs in one sequential draw.io batch."""
import argparse
import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render', action='store_true', help='Export paired PNGs with draw.io Desktop')
    parser.add_argument('--overviews-only', action='store_true', help='Export only overview PNGs after rebuilding native pages')
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location('connections', Path(__file__).with_name('check-connections.py'))
    review = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(review)
    overviews = list(review.diagrams())
    targets = [(ROOT / 'blueprints' / slug / 'architecture/architecture.drawio', d) for slug, d in overviews]
    targets.append((ROOT / 'docs/diagrams/oci-3tier-adb.drawio', review.load('conceptual-three-tier').build()))
    for path, diagram in targets:
        warnings = diagram.check() + diagram._crossings([n for n in diagram.nodes if n.kind == 'text'])
        if warnings:
            raise RuntimeError((path, warnings))
        diagram.save(str(path))
        with path.open('a') as stream:
            stream.write('\n')
    print(f'Rebuilt {len(targets)} overviews', flush=True)
    command = [sys.executable, str(Path(__file__).with_name('multicloud-resource-coverage.py'))]
    for slug, _ in overviews:
        command.extend(['--blueprint', slug])
    subprocess.run(command, cwd=ROOT, check=True)
    if not args.render:
        return
    binary = shutil.which('drawio') or shutil.which('draw.io')
    if not binary:
        candidate = Path('/Applications/draw.io.app/Contents/MacOS/draw.io')
        if candidate.is_file():
            binary = str(candidate)
    if not binary:
        raise RuntimeError('draw.io Desktop CLI is required for PNG export')
    names = subprocess.check_output(['rg', '--files', '-g', '*.drawio', '-g', '!**/.terraform/**'], cwd=ROOT, text=True).splitlines()
    natives = [path for path, _ in targets] if args.overviews_only else [ROOT / name for name in sorted(names)]
    # The native files are generated by their authoring builders above. Export
    # copies only avoid output-name collisions; no XML or raster editing occurs.
    with tempfile.TemporaryDirectory(prefix='oci-diagram-export-') as temp:
        incoming, outgoing = Path(temp) / 'input', Path(temp) / 'output'
        incoming.mkdir()
        outgoing.mkdir()
        for i, path in enumerate(natives):
            shutil.copyfile(path, incoming / f'{i:04}.drawio')
        print(f'Exporting {len(natives)} PNGs sequentially through draw.io', flush=True)
        export = [binary, '-x', '-f', 'png', '-s', '1.5', '-b', '20', '-o', str(outgoing), str(incoming), '--no-sandbox', '--disable-gpu']
        if sys.platform.startswith('linux') and not os.environ.get('DISPLAY') and shutil.which('xvfb-run'):
            export = ['xvfb-run', '-a'] + export
        subprocess.run(export, check=True)
        for i, path in enumerate(natives):
            png = outgoing / f'{i:04}.png'
            if not png.is_file() or not png.read_bytes().startswith(b'\x89PNG\r\n\x1a\n'):
                raise RuntimeError('Missing or invalid PNG: ' + str(path))
        for i, path in enumerate(natives):
            target = path.with_suffix('.png')
            temporary = target.with_suffix('.png.tmp')
            shutil.copyfile(outgoing / f'{i:04}.png', temporary)
            temporary.replace(target)
    print(f'Completed {len(natives)} paired native/PNG documents', flush=True)


if __name__ == '__main__':
    main()
